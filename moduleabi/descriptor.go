// Package moduleabi describes and validates the finite independent-module ABI.
// It derives the descriptor from AppIR and exact generated artifact bytes.
package moduleabi

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"path"
	"regexp"
	"sort"
	"strings"
	"unicode/utf8"

	"github.com/samuelpmahan/gondola/compilercontract"
)

const (
	Schema        = "gobi.module-abi/v1"
	WirePackage   = "github.com/samuelpmahan/gondola/fixtures/compiled/modulewire"
	InputTypeID   = compilercontract.TypeID(WirePackage + ".Input")
	PublicationID = compilercontract.TypeID(WirePackage + ".Publication")
)

var identifierPattern = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_.:/-]*$`)
var sha256Pattern = regexp.MustCompile(`^[0-9a-f]{64}$`)

const maxSafeJSONInteger int64 = 9007199254740991

// Artifact describes one exact output file used to bind a module descriptor.
// The ABI descriptor and buildmanifest are deliberately excluded to avoid a
// self-referential hash. artifactFiles must contain all files listed here and
// no others.
type Artifact struct {
	Path   string `json:"path"`
	Bytes  int64  `json:"bytes"`
	SHA256 string `json:"sha256"`
}

// Role names are the exported Go function names. Symbol and Signature are
// copied from the source-derived AppIR, never supplied as independent types.
type Role struct {
	Name      string                     `json:"name"`
	Symbol    compilercontract.SymbolID  `json:"symbol"`
	Signature compilercontract.Signature `json:"signature"`
}

// Descriptor is the closed, artifact-bound ABI for one separately built app.
// Roles and Types are canonicalized by name and TypeID respectively; fields
// within each TypeInfo keep their Go declaration order.
type Descriptor struct {
	Schema         string                        `json:"schema"`
	AppIRSchema    string                        `json:"appIRSchema"`
	ComponentID    string                        `json:"componentID"`
	PackagePath    string                        `json:"packagePath"`
	ArtifactSHA256 string                        `json:"artifactSHA256"`
	Artifacts      []Artifact                    `json:"artifacts"`
	Roles          []Role                        `json:"roles"`
	Types          []compilercontract.TypeInfo   `json:"types"`
	Capabilities   []compilercontract.Capability `json:"capabilities"`
	ABISHA256      string                        `json:"abiSHA256,omitempty"`
}

// Describe derives the ABI from the actual AppIR and generated bytes. Artifact
// paths must be output-relative, unique, and non-empty. The bridge role set
// must be either the complete parent pair (Output/Receive) or the complete
// child pair (Input/Publication).
func Describe(appIR compilercontract.AppIR, artifactFiles map[string][]byte) (Descriptor, error) {
	if appIR.Schema != compilercontract.AppIRSchema {
		return Descriptor{}, fmt.Errorf("appIR schema must be %q", compilercontract.AppIRSchema)
	}
	if len(appIR.Components) != 1 {
		return Descriptor{}, fmt.Errorf("module ABI requires exactly one component, got %d", len(appIR.Components))
	}
	if appIR.Components == nil || appIR.Symbols == nil || appIR.Types == nil {
		return Descriptor{}, errors.New("appIR components, symbols, and types must be non-null arrays")
	}
	component := appIR.Components[0]
	if component.ID == "" || component.PackagePath == "" || component.PackagePath != appIR.PackagePath {
		return Descriptor{}, errors.New("component identity must match the AppIR package")
	}
	if diagnostics := compilercontract.ValidateAppIR(appIR); len(diagnostics) != 0 {
		return Descriptor{}, fmt.Errorf("invalid AppIR: %s", diagnostics[0].Message)
	}
	if len(artifactFiles) == 0 {
		return Descriptor{}, errors.New("module ABI requires generated artifacts")
	}
	if err := validateArtifactFiles(artifactFiles); err != nil {
		return Descriptor{}, err
	}
	appIRPath := ""
	for name := range artifactFiles {
		if path.Base(name) == "app-ir.json" {
			appIRPath = name
		}
	}
	serializedAppIR, err := json.Marshal(appIR)
	if err != nil {
		return Descriptor{}, fmt.Errorf("marshal source AppIR: %w", err)
	}
	if !bytes.Equal(serializedAppIR, artifactFiles[appIRPath]) {
		return Descriptor{}, errors.New("app-ir.json bytes do not equal the supplied source-derived AppIR")
	}

	symbols := make(map[compilercontract.SymbolID]compilercontract.Symbol, len(appIR.Symbols))
	for _, symbol := range appIR.Symbols {
		if _, exists := symbols[symbol.ID]; exists {
			return Descriptor{}, fmt.Errorf("duplicate AppIR symbol %q", symbol.ID)
		}
		symbols[symbol.ID] = symbol
	}
	roleIDs := map[string]compilercontract.SymbolID{
		"Init":   component.Init,
		"Update": component.Update,
		"View":   component.View,
	}
	bridgeNames := map[string]bool{"Output": true, "Receive": true, "Input": true, "Publication": true}
	for _, symbol := range appIR.Symbols {
		if symbol.PackagePath != component.PackagePath || !bridgeNames[symbol.Name] {
			continue
		}
		if _, duplicate := roleIDs[symbol.Name]; duplicate {
			return Descriptor{}, fmt.Errorf("duplicate bridge role %q", symbol.Name)
		}
		if symbol.ID != compilercontract.SymbolID(component.PackagePath+"."+symbol.Name) {
			return Descriptor{}, fmt.Errorf("bridge role %q has non-canonical symbol ID %q", symbol.Name, symbol.ID)
		}
		roleIDs[symbol.Name] = symbol.ID
	}
	parentPair := roleIDs["Output"] != "" && roleIDs["Receive"] != ""
	childPair := roleIDs["Input"] != "" && roleIDs["Publication"] != ""
	if parentPair == childPair {
		return Descriptor{}, errors.New("module must declare exactly one complete bridge pair: Output/Receive or Input/Publication")
	}
	if parentPair && (roleIDs["Input"] != "" || roleIDs["Publication"] != "") {
		return Descriptor{}, errors.New("parent module cannot also declare child bridge roles")
	}
	if childPair && (roleIDs["Output"] != "" || roleIDs["Receive"] != "") {
		return Descriptor{}, errors.New("child module cannot also declare parent bridge roles")
	}

	roleNames := make([]string, 0, len(roleIDs))
	for name := range roleIDs {
		roleNames = append(roleNames, name)
	}
	sort.Strings(roleNames)
	roles := make([]Role, 0, len(roleNames))
	typeRoots := make([]compilercontract.TypeID, 0, len(roleNames)*3+2)
	typeRoots = append(typeRoots, component.StateType, component.MessageType)
	for _, name := range roleNames {
		symbol, ok := symbols[roleIDs[name]]
		if !ok {
			return Descriptor{}, fmt.Errorf("role %q refers to missing symbol %q", name, roleIDs[name])
		}
		if symbol.PackagePath != component.PackagePath || symbol.Name != name {
			return Descriptor{}, fmt.Errorf("role %q symbol does not match component package/name", name)
		}
		roles = append(roles, Role{Name: name, Symbol: symbol.ID, Signature: symbol.Signature})
		typeRoots = append(typeRoots, symbol.Signature.Params...)
		typeRoots = append(typeRoots, symbol.Signature.Results...)
	}
	types, err := typeClosure(appIR.Types, typeRoots)
	if err != nil {
		return Descriptor{}, err
	}
	capabilities, err := canonicalCapabilities(component.Capabilities)
	if err != nil {
		return Descriptor{}, err
	}
	artifacts, artifactHash, err := describeArtifacts(artifactFiles)
	if err != nil {
		return Descriptor{}, err
	}
	d := Descriptor{
		Schema: Schema, AppIRSchema: appIR.Schema, ComponentID: component.ID,
		PackagePath: component.PackagePath, ArtifactSHA256: artifactHash,
		Artifacts: artifacts, Roles: roles, Types: types, Capabilities: capabilities,
	}
	d.ABISHA256, err = descriptorDigest(d)
	if err != nil {
		return Descriptor{}, err
	}
	if err := ValidateDescriptor(d); err != nil {
		return Descriptor{}, err
	}
	return d, nil
}

// ValidateDescriptor verifies the closed descriptor's shape, internal role
// signatures, canonical ordering, capability policy, and ABI digest.
func ValidateDescriptor(d Descriptor) error {
	if d.Schema != Schema || d.AppIRSchema != compilercontract.AppIRSchema {
		return errors.New("unsupported module ABI or AppIR schema")
	}
	if !identifierPattern.MatchString(d.ComponentID) || d.PackagePath == "" || !validPackagePath(d.PackagePath) {
		return errors.New("invalid module component or package identity")
	}
	if d.Artifacts == nil || len(d.Artifacts) == 0 || d.Roles == nil || d.Types == nil || d.Capabilities == nil {
		return errors.New("module ABI arrays must be present and non-null")
	}
	if !sha256Pattern.MatchString(d.ArtifactSHA256) || !sha256Pattern.MatchString(d.ABISHA256) {
		return errors.New("module ABI digests must be lowercase SHA-256 hex")
	}
	if err := validateArtifactRecords(d.Artifacts); err != nil {
		return err
	}
	if err := validateArtifactInventory(d.Artifacts); err != nil {
		return err
	}
	artifactHash, err := digestJSON(d.Artifacts)
	if err != nil {
		return err
	}
	if artifactHash != d.ArtifactSHA256 {
		return errors.New("artifact digest does not match artifact inventory")
	}
	if err := validateRoles(d); err != nil {
		return err
	}
	if err := validateTypes(d.Types); err != nil {
		return err
	}
	canonicalCaps, err := canonicalCapabilities(d.Capabilities)
	if err != nil {
		return err
	}
	if !equalCapabilities(canonicalCaps, d.Capabilities) {
		return errors.New("capabilities must be unique and sorted")
	}
	hasEffectRequest, hasEffectCancel := false, false
	for _, capability := range d.Capabilities {
		switch capability {
		case compilercontract.CapabilityEffectRequest:
			hasEffectRequest = true
		case compilercontract.CapabilityEffectCancel:
			hasEffectCancel = true
		}
	}
	roles := roleMap(d.Roles)
	types := typeMap(d.Types)
	parent := roles["Output"].Name != ""
	// Effect capabilities describe declared typed child code. They do not
	// certify the host effect vocabulary or lifecycle; profile admission owns
	// those exact descriptors. Parent effect ABIs remain outside this v1 shape.
	if (hasEffectRequest || hasEffectCancel) && (roles["Input"].Name == "" || roles["Publication"].Name == "") {
		return errors.New("effect capabilities require the child Input/Publication bridge roles")
	}
	if err := validateBridgeSignature(roles, types, parent); err != nil {
		return err
	}
	if err := validateWireTypes(types); err != nil {
		return err
	}
	if err := validateExactTypeClosure(d); err != nil {
		return err
	}
	want, err := descriptorDigest(d)
	if err != nil {
		return err
	}
	if want != d.ABISHA256 {
		return errors.New("ABI digest does not match descriptor")
	}
	return nil
}

// ValidatePair admits only the frozen one-parent/one-child bridge pair with
// exact nominal shared wire types. State and message types remain module-local.
func ValidatePair(parent, child Descriptor) error {
	if err := ValidateDescriptor(parent); err != nil {
		return fmt.Errorf("parent descriptor: %w", err)
	}
	if err := ValidateDescriptor(child); err != nil {
		return fmt.Errorf("child descriptor: %w", err)
	}
	if parent.ComponentID == child.ComponentID || parent.PackagePath == child.PackagePath {
		return errors.New("parent and child must be independently identified modules")
	}
	parentRoles := roleMap(parent.Roles)
	childRoles := roleMap(child.Roles)
	if !hasExactRoleSet(parentRoles, "Init", "Update", "View", "Output", "Receive") {
		return errors.New("parent must expose exactly Init, Update, View, Output, and Receive")
	}
	if !hasExactRoleSet(childRoles, "Init", "Update", "View", "Input", "Publication") {
		return errors.New("child must expose exactly Init, Update, View, Input, and Publication")
	}
	parentTypes := typeMap(parent.Types)
	childTypes := typeMap(child.Types)
	if err := validateBridgeSignature(parentRoles, parentTypes, true); err != nil {
		return fmt.Errorf("parent bridge signature: %w", err)
	}
	if err := validateBridgeSignature(childRoles, childTypes, false); err != nil {
		return fmt.Errorf("child bridge signature: %w", err)
	}
	if err := validateWireTypes(parentTypes); err != nil {
		return fmt.Errorf("parent wire types: %w", err)
	}
	if err := validateWireTypes(childTypes); err != nil {
		return fmt.Errorf("child wire types: %w", err)
	}
	for _, id := range []compilercontract.TypeID{InputTypeID, PublicationID} {
		parentType, parentOK := parentTypes[id]
		childType, childOK := childTypes[id]
		if !parentOK || !childOK {
			return fmt.Errorf("both modules must declare nominal wire type %q", id)
		}
		if !typeInfoEqual(parentType, childType) {
			return fmt.Errorf("wire type %q differs between modules", id)
		}
	}
	return nil
}

// ValidateArtifactBytes verifies a decoded descriptor against the exact bytes
// supplied for its four generated artifacts. It also requires the app-ir.json
// payload to match the caller's source-derived AppIR when that is compared by
// Describe.
func ValidateArtifactBytes(d Descriptor, files map[string][]byte) error {
	if err := ValidateDescriptor(d); err != nil {
		return err
	}
	if err := validateArtifactFiles(files); err != nil {
		return err
	}
	actual, _, err := describeArtifacts(files)
	if err != nil {
		return err
	}
	if len(actual) != len(d.Artifacts) {
		return errors.New("artifact byte set does not match descriptor inventory")
	}
	for i := range actual {
		if actual[i] != d.Artifacts[i] {
			return fmt.Errorf("artifact bytes mismatch for %q", d.Artifacts[i].Path)
		}
	}
	return nil
}

// MarshalDescriptor validates and returns the JSON representation consumed by
// buildmanifest.moduleABI. It includes no caller-dependent indentation.
func MarshalDescriptor(d Descriptor) ([]byte, error) {
	if err := ValidateDescriptor(d); err != nil {
		return nil, err
	}
	return json.Marshal(d)
}

// DecodeDescriptorJSON rejects duplicate object members, unknown fields,
// trailing values, invalid UTF-8, missing required values, and digest errors.
func DecodeDescriptorJSON(data []byte) (Descriptor, error) {
	if !utf8.Valid(data) {
		return Descriptor{}, errors.New("descriptor JSON is not valid UTF-8")
	}
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.UseNumber()
	raw, err := consumeJSON(decoder)
	if err != nil {
		return Descriptor{}, err
	}
	if _, err := decoder.Token(); err != io.EOF {
		if err == nil {
			return Descriptor{}, errors.New("trailing JSON value")
		}
		return Descriptor{}, err
	}
	if err := validateDescriptorJSONShape(raw); err != nil {
		return Descriptor{}, err
	}
	var d Descriptor
	strict := json.NewDecoder(bytes.NewReader(data))
	strict.DisallowUnknownFields()
	if err := strict.Decode(&d); err != nil {
		return Descriptor{}, err
	}
	if err := ValidateDescriptor(d); err != nil {
		return Descriptor{}, err
	}
	return d, nil
}

func validateDescriptorJSONShape(raw any) error {
	descriptor, err := objectAt(raw, "$", []string{
		"schema", "appIRSchema", "componentID", "packagePath", "artifactSHA256",
		"artifacts", "roles", "types", "capabilities", "abiSHA256",
	}, nil)
	if err != nil {
		return err
	}
	artifacts, err := arrayAt(descriptor["artifacts"], "$.artifacts")
	if err != nil {
		return err
	}
	for index, rawArtifact := range artifacts {
		if _, err := objectAt(rawArtifact, fmt.Sprintf("$.artifacts[%d]", index), []string{"path", "bytes", "sha256"}, nil); err != nil {
			return err
		}
	}
	roles, err := arrayAt(descriptor["roles"], "$.roles")
	if err != nil {
		return err
	}
	for index, rawRole := range roles {
		rolePath := fmt.Sprintf("$.roles[%d]", index)
		role, err := objectAt(rawRole, rolePath, []string{"name", "symbol", "signature"}, nil)
		if err != nil {
			return err
		}
		signature, err := objectAt(role["signature"], rolePath+".signature", []string{"params", "results"}, nil)
		if err != nil {
			return err
		}
		if _, err := arrayAt(signature["params"], rolePath+".signature.params"); err != nil {
			return err
		}
		if _, err := arrayAt(signature["results"], rolePath+".signature.results"); err != nil {
			return err
		}
	}
	types, err := arrayAt(descriptor["types"], "$.types")
	if err != nil {
		return err
	}
	for index, rawType := range types {
		typePath := fmt.Sprintf("$.types[%d]", index)
		typeRecord, err := objectAt(rawType, typePath, []string{"id", "kind"}, []string{"bits", "elemType", "length", "fields", "jsRepresentation"})
		if err != nil {
			return err
		}
		if fieldsRaw, exists := typeRecord["fields"]; exists {
			fields, err := arrayAt(fieldsRaw, typePath+".fields")
			if err != nil {
				return err
			}
			for fieldIndex, rawField := range fields {
				if _, err := objectAt(rawField, fmt.Sprintf("%s.fields[%d]", typePath, fieldIndex), []string{"name", "type"}, nil); err != nil {
					return err
				}
			}
		}
	}
	if _, err := arrayAt(descriptor["capabilities"], "$.capabilities"); err != nil {
		return err
	}
	return nil
}

func objectAt(raw any, location string, required, optional []string) (map[string]any, error) {
	object, ok := raw.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("%s must be an object", location)
	}
	allowed := make(map[string]bool, len(required)+len(optional))
	for _, name := range required {
		allowed[name] = true
		if _, exists := object[name]; !exists {
			return nil, fmt.Errorf("%s is missing required property %q", location, name)
		}
	}
	for _, name := range optional {
		allowed[name] = true
	}
	for name := range object {
		if !allowed[name] {
			return nil, fmt.Errorf("%s has unknown property %q", location, name)
		}
	}
	return object, nil
}

func arrayAt(raw any, location string) ([]any, error) {
	array, ok := raw.([]any)
	if !ok || array == nil {
		return nil, fmt.Errorf("%s must be a non-null array", location)
	}
	return array, nil
}

func validPackagePath(value string) bool {
	if value == "" || strings.ContainsAny(value, "\\\x00") || strings.HasPrefix(value, "/") || strings.HasSuffix(value, "/") {
		return false
	}
	for _, segment := range strings.Split(value, "/") {
		if segment == "" || segment == "." || segment == ".." || !identifierPattern.MatchString(segment) {
			return false
		}
	}
	return true
}

func describeArtifacts(files map[string][]byte) ([]Artifact, string, error) {
	paths := make([]string, 0, len(files))
	for name := range files {
		if !validArtifactPath(name) {
			return nil, "", fmt.Errorf("invalid artifact path %q", name)
		}
		paths = append(paths, name)
	}
	sort.Strings(paths)
	artifacts := make([]Artifact, 0, len(paths))
	for _, name := range paths {
		data := files[name]
		if len(data) == 0 {
			return nil, "", fmt.Errorf("artifact %q is empty", name)
		}
		hash := sha256.Sum256(data)
		artifacts = append(artifacts, Artifact{Path: name, Bytes: int64(len(data)), SHA256: hex.EncodeToString(hash[:])})
	}
	digest, err := digestJSON(artifacts)
	return artifacts, digest, err
}

func validArtifactPath(value string) bool {
	if value == "" || strings.ContainsAny(value, "\\\x00") || strings.HasPrefix(value, "/") || path.Clean(value) != value {
		return false
	}
	if value == "." || value == ".." || strings.HasPrefix(value, "../") {
		return false
	}
	return true
}

func validateArtifactRecords(artifacts []Artifact) error {
	last := ""
	for index, artifact := range artifacts {
		if !validArtifactPath(artifact.Path) || artifact.Bytes <= 0 || artifact.Bytes > maxSafeJSONInteger || !sha256Pattern.MatchString(artifact.SHA256) {
			return fmt.Errorf("invalid artifact record at index %d", index)
		}
		if index > 0 && artifact.Path <= last {
			return errors.New("artifact paths must be unique and sorted")
		}
		last = artifact.Path
	}
	return nil
}

func validateArtifactInventory(artifacts []Artifact) error {
	if len(artifacts) != 4 {
		return fmt.Errorf("module artifact inventory must contain exactly four generated files, got %d", len(artifacts))
	}
	expected := map[string]bool{
		"app-ir.json":        false,
		"gobi-compiled.mjs":  false,
		"encoder.mjs":        false,
		"components.gen.mjs": false,
	}
	appDir := ""
	for _, artifact := range artifacts {
		base := path.Base(artifact.Path)
		if _, known := expected[base]; !known || expected[base] {
			return fmt.Errorf("unexpected or repeated module artifact %q", artifact.Path)
		}
		expected[base] = true
		directory := path.Dir(artifact.Path)
		if !strings.HasPrefix(directory, "apps/") || strings.Count(directory, "/") != 1 {
			return fmt.Errorf("module artifact %q must be directly under apps/<appDir>", artifact.Path)
		}
		if appDir == "" {
			appDir = directory
		} else if appDir != directory {
			return errors.New("module artifacts must belong to exactly one apps/<appDir>")
		}
	}
	for name, present := range expected {
		if !present {
			return fmt.Errorf("module artifact inventory is missing %q", name)
		}
	}
	return nil
}

func validateArtifactFiles(files map[string][]byte) error {
	artifacts, _, err := describeArtifacts(files)
	if err != nil {
		return err
	}
	return validateArtifactInventory(artifacts)
}

func validateRoles(d Descriptor) error {
	if len(d.Roles) != 5 {
		return fmt.Errorf("module descriptor must have three conventional roles and one complete bridge pair, got %d roles", len(d.Roles))
	}
	last := ""
	seen := map[string]bool{}
	for i, role := range d.Roles {
		if role.Name == "" || role.Symbol == "" || role.Symbol != compilercontract.SymbolID(d.PackagePath+"."+role.Name) {
			return fmt.Errorf("invalid role identity at index %d", i)
		}
		if i > 0 && role.Name <= last {
			return errors.New("roles must be unique and sorted by name")
		}
		last = role.Name
		seen[role.Name] = true
		if role.Signature.Params == nil || role.Signature.Results == nil {
			return fmt.Errorf("role %q signature arrays must be present", role.Name)
		}
	}
	parentPair := seen["Output"] && seen["Receive"] && !seen["Input"] && !seen["Publication"]
	childPair := seen["Input"] && seen["Publication"] && !seen["Output"] && !seen["Receive"]
	if !(parentPair || childPair) || !seen["Init"] || !seen["Update"] || !seen["View"] {
		return errors.New("role names must be Init/Update/View plus exactly one bridge pair")
	}
	return nil
}

func validateTypes(types []compilercontract.TypeInfo) error {
	if types == nil || len(types) == 0 {
		return errors.New("type closure must be present and non-empty")
	}
	last := compilercontract.TypeID("")
	index := make(map[compilercontract.TypeID]compilercontract.TypeInfo, len(types))
	for i, info := range types {
		if info.ID == "" || (i > 0 && info.ID <= last) {
			return errors.New("type closure IDs must be unique and sorted")
		}
		last = info.ID
		index[info.ID] = info
	}
	for _, info := range types {
		switch info.Kind {
		case compilercontract.KindBool, compilercontract.KindString, compilercontract.KindInt, compilercontract.KindUint, compilercontract.KindFloat64:
			if info.Fields != nil || info.ElemType != "" || info.Length != nil {
				return fmt.Errorf("scalar type %q has composite metadata", info.ID)
			}
		case compilercontract.KindStruct:
			if info.Fields == nil || len(info.Fields) == 0 || info.ElemType != "" || info.Length != nil {
				return fmt.Errorf("struct type %q has invalid fields", info.ID)
			}
			fieldNames := map[string]bool{}
			for _, field := range info.Fields {
				if field.Name == "" || field.Type == "" || fieldNames[field.Name] {
					return fmt.Errorf("struct type %q has invalid or duplicate field", info.ID)
				}
				fieldNames[field.Name] = true
				if _, ok := index[field.Type]; !ok {
					return fmt.Errorf("struct type %q refers to missing field type %q", info.ID, field.Type)
				}
			}
		case compilercontract.KindSlice:
			if info.ElemType == "" || info.Fields != nil || info.Length != nil {
				return fmt.Errorf("slice type %q has invalid element metadata", info.ID)
			}
			if _, ok := index[info.ElemType]; !ok {
				return fmt.Errorf("slice type %q refers to missing element type %q", info.ID, info.ElemType)
			}
		case compilercontract.KindArray:
			if info.ElemType == "" || info.Fields != nil || info.Length == nil || *info.Length < 0 || int64(*info.Length) > maxSafeJSONInteger {
				return fmt.Errorf("array type %q has invalid metadata", info.ID)
			}
			if _, ok := index[info.ElemType]; !ok {
				return fmt.Errorf("array type %q refers to missing element type %q", info.ID, info.ElemType)
			}
		default:
			return fmt.Errorf("unsupported type kind %q", info.Kind)
		}
		if info.Kind == compilercontract.KindInt || info.Kind == compilercontract.KindUint {
			if info.Bits != 8 && info.Bits != 16 && info.Bits != 32 && info.Bits != 64 {
				return fmt.Errorf("integer type %q has unsupported bit width %d", info.ID, info.Bits)
			}
		} else if info.Bits != 0 {
			return fmt.Errorf("non-integer type %q declares bit width", info.ID)
		}
		if !validRepresentation(info) {
			return fmt.Errorf("type %q has incompatible JS representation %q", info.ID, info.JSRepresentation)
		}
	}
	return nil
}

func validRepresentation(info compilercontract.TypeInfo) bool {
	switch info.Kind {
	case compilercontract.KindBool, compilercontract.KindString:
		return info.JSRepresentation == compilercontract.JSDirect
	case compilercontract.KindInt, compilercontract.KindUint:
		if info.Bits == 64 && (info.ID == "int64" || info.ID == "uint64") {
			return info.JSRepresentation == compilercontract.JSBigInt
		}
		return info.JSRepresentation == compilercontract.JSNumber
	case compilercontract.KindFloat64:
		return info.JSRepresentation == compilercontract.JSNumber
	case compilercontract.KindStruct:
		return info.JSRepresentation == compilercontract.JSClass
	case compilercontract.KindSlice:
		return info.JSRepresentation == compilercontract.JSSliceWrapper || info.JSRepresentation == compilercontract.JSArrayOrSlice || info.JSRepresentation == compilercontract.JSFloat64ArrayOrSlice || info.JSRepresentation == compilercontract.JSFloat64Array || info.JSRepresentation == compilercontract.JSArray
	case compilercontract.KindArray:
		return info.JSRepresentation == compilercontract.JSArray || info.JSRepresentation == compilercontract.JSFloat64Array
	default:
		return false
	}
}

func typeClosure(all []compilercontract.TypeInfo, roots []compilercontract.TypeID) ([]compilercontract.TypeInfo, error) {
	index := make(map[compilercontract.TypeID]compilercontract.TypeInfo, len(all))
	for _, info := range all {
		if _, duplicate := index[info.ID]; duplicate {
			return nil, fmt.Errorf("duplicate AppIR type %q", info.ID)
		}
		index[info.ID] = info
	}
	visited := map[compilercontract.TypeID]bool{}
	var visit func(compilercontract.TypeID) error
	visit = func(id compilercontract.TypeID) error {
		if visited[id] {
			return nil
		}
		info, ok := index[id]
		if !ok {
			return fmt.Errorf("AppIR role refers to unknown type %q", id)
		}
		// Type closures can be recursive through named slices (for example
		// gobi.Node.Kids []gobi.Node). Mark before traversing outgoing edges.
		visited[id] = true
		for _, field := range info.Fields {
			if err := visit(field.Type); err != nil {
				return err
			}
		}
		if info.ElemType != "" {
			if err := visit(info.ElemType); err != nil {
				return err
			}
		}
		return nil
	}
	for _, id := range roots {
		if err := visit(id); err != nil {
			return nil, err
		}
	}
	ids := make([]compilercontract.TypeID, 0, len(visited))
	for id := range visited {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })
	out := make([]compilercontract.TypeInfo, 0, len(ids))
	for _, id := range ids {
		out = append(out, index[id])
	}
	return out, nil
}

func canonicalCapabilities(values []compilercontract.Capability) ([]compilercontract.Capability, error) {
	known := map[compilercontract.Capability]bool{
		compilercontract.CapabilityViewNode:       true,
		compilercontract.CapabilityBindingValue:   true,
		compilercontract.CapabilityBindingChecked: true,
		compilercontract.CapabilitySafeInteger:    true,
		compilercontract.CapabilityFloat64:        true,
		compilercontract.CapabilityEffectRequest:  true,
		compilercontract.CapabilityEffectCancel:   true,
	}
	seen := map[compilercontract.Capability]bool{}
	for _, capability := range values {
		if !known[capability] {
			return nil, fmt.Errorf("unsupported or effect capability %q", capability)
		}
		if seen[capability] {
			return nil, fmt.Errorf("duplicate capability %q", capability)
		}
		seen[capability] = true
	}
	if !seen[compilercontract.CapabilityViewNode] {
		return nil, errors.New("module must declare view.node capability")
	}
	out := append([]compilercontract.Capability{}, values...)
	sort.Slice(out, func(i, j int) bool { return out[i] < out[j] })
	return out, nil
}

