func validateBridgeSignature(roles map[string]Role, types map[compilercontract.TypeID]compilercontract.TypeInfo, parent bool) error {
	init := roles["Init"].Signature
	state := init.Results
	if len(init.Params) != 0 || len(state) != 1 || state[0] == "" {
		return errors.New("Init must return one state")
	}
	stateID := state[0]
	stateType, ok := types[stateID]
	if !ok || stateType.Kind != compilercontract.KindStruct {
		return errors.New("Init state type must be a declared struct")
	}
	update := roles["Update"].Signature
	if len(update.Params) != 2 || update.Params[0] != stateID || len(update.Results) != 2 || update.Results[0] != stateID {
		return errors.New("Update must accept state/message and return state/effects")
	}
	messageType, ok := types[update.Params[1]]
	if !ok || messageType.Kind != compilercontract.KindStruct || fieldType(messageType, "Name") != "string" || fieldType(messageType, "Arg") != "string" {
		return errors.New("Update message must be a struct with string Name and Arg fields")
	}
	effects, ok := types[update.Results[1]]
	if !ok || effects.Kind != compilercontract.KindSlice {
		return errors.New("Update effects result must be a slice")
	}
	effectType, ok := types[effects.ElemType]
	if !ok || effectType.Kind != compilercontract.KindStruct || !strings.HasSuffix(string(effectType.ID), ".Effect") || fieldType(effectType, "Kind") != "string" || fieldType(effectType, "Name") != "string" || fieldType(effectType, "Arg") != "string" || fieldType(effectType, "Reply") != "string" {
		return errors.New("Update effects must be a slice of gobi.Effect-shaped values")
	}
	view := roles["View"].Signature
	if len(view.Params) != 1 || view.Params[0] != stateID || len(view.Results) != 1 {
		return errors.New("View must accept state and return one view")
	}
	viewType, ok := types[view.Results[0]]
	if !ok || viewType.Kind != compilercontract.KindStruct || !(strings.HasSuffix(string(viewType.ID), ".Node") || viewType.ID == "github.com/samuelpmahan/gondola/compilercontract.View") {
		return errors.New("View must return a supported Node or compilercontract.View type")
	}
	if parent {
		output := roles["Output"].Signature
		receive := roles["Receive"].Signature
		if len(output.Params) != 1 || output.Params[0] != stateID || len(output.Results) != 1 || output.Results[0] != InputTypeID {
			return errors.New("Output must have signature func(State) modulewire.Input")
		}
		if len(receive.Params) != 2 || receive.Params[0] != stateID || receive.Params[1] != PublicationID || len(receive.Results) != 1 || receive.Results[0] != stateID {
			return errors.New("Receive must have signature func(State, modulewire.Publication) State")
		}
	} else {
		input := roles["Input"].Signature
		publication := roles["Publication"].Signature
		if len(input.Params) != 2 || input.Params[0] != stateID || input.Params[1] != InputTypeID || len(input.Results) != 1 || input.Results[0] != stateID {
			return errors.New("Input must have signature func(State, modulewire.Input) State")
		}
		if len(publication.Params) != 1 || publication.Params[0] != stateID || len(publication.Results) != 1 || publication.Results[0] != PublicationID {
			return errors.New("Publication must have signature func(State) modulewire.Publication")
		}
	}
	return nil
}

func fieldType(info compilercontract.TypeInfo, name string) compilercontract.TypeID {
	for _, field := range info.Fields {
		if field.Name == name {
			return field.Type
		}
	}
	return ""
}

func validateExactTypeClosure(d Descriptor) error {
	roots := make([]compilercontract.TypeID, 0, len(d.Roles)*3)
	for _, role := range d.Roles {
		roots = append(roots, role.Signature.Params...)
		roots = append(roots, role.Signature.Results...)
	}
	closure, err := typeClosure(d.Types, roots)
	if err != nil {
		return err
	}
	if len(closure) != len(d.Types) {
		return errors.New("descriptor types are not the exact role-reachable type closure")
	}
	for index := range closure {
		if !typeInfoEqual(closure[index], d.Types[index]) {
			return fmt.Errorf("type %q differs from its reachable TypeInfo", d.Types[index].ID)
		}
	}
	return nil
}

func equalCapabilities(left, right []compilercontract.Capability) bool {
	if len(left) != len(right) {
		return false
	}
	for i := range left {
		if left[i] != right[i] {
			return false
		}
	}
	return true
}

func validateWireTypes(types map[compilercontract.TypeID]compilercontract.TypeInfo) error {
	input, ok := types[InputTypeID]
	if !ok || input.Kind != compilercontract.KindStruct || input.JSRepresentation != compilercontract.JSClass || len(input.Fields) != 3 {
		return errors.New("modulewire.Input must be the declared three-field struct")
	}
	publication, ok := types[PublicationID]
	if !ok || publication.Kind != compilercontract.KindStruct || publication.JSRepresentation != compilercontract.JSClass || len(publication.Fields) != 2 {
		return errors.New("modulewire.Publication must be the declared two-field struct")
	}
	if input.Fields[0] != (compilercontract.TypeField{Name: "Step", Type: "int"}) || input.Fields[1] != (compilercontract.TypeField{Name: "Locked", Type: "bool"}) || input.Fields[2] != (compilercontract.TypeField{Name: "Revision", Type: "int"}) {
		return errors.New("modulewire.Input fields or field order differ from the frozen ABI")
	}
	if publication.Fields[0] != (compilercontract.TypeField{Name: "Count", Type: "float64"}) || publication.Fields[1] != (compilercontract.TypeField{Name: "Revision", Type: "int"}) {
		return errors.New("modulewire.Publication fields or field order differ from the frozen ABI")
	}
	for _, id := range []compilercontract.TypeID{"int", "bool", "float64"} {
		if _, ok := types[id]; !ok {
			return fmt.Errorf("modulewire field type %q is missing", id)
		}
	}
	intType := types["int"]
	boolType := types["bool"]
	floatType := types["float64"]
	if intType.Kind != compilercontract.KindInt || intType.Bits != 64 || intType.JSRepresentation != compilercontract.JSNumber {
		return errors.New("wire int must be a 64-bit Go int represented as a JavaScript number")
	}
	if boolType.Kind != compilercontract.KindBool || boolType.JSRepresentation != compilercontract.JSDirect {
		return errors.New("wire bool must be represented directly")
	}
	if floatType.Kind != compilercontract.KindFloat64 || floatType.JSRepresentation != compilercontract.JSNumber {
		return errors.New("wire float64 must be represented as a JavaScript number")
	}
	return nil
}

func typeInfoEqual(a, b compilercontract.TypeInfo) bool {
	left, _ := json.Marshal(a)
	right, _ := json.Marshal(b)
	return bytes.Equal(left, right)
}

func descriptorDigest(d Descriptor) (string, error) {
	d.ABISHA256 = ""
	return digestJSON(d)
}

func digestJSON(value any) (string, error) {
	encoded, err := json.Marshal(value)
	if err != nil {
		return "", err
	}
	var normalized any
	decoder := json.NewDecoder(bytes.NewReader(encoded))
	decoder.UseNumber()
	if err := decoder.Decode(&normalized); err != nil {
		return "", err
	}
	canonical, err := canonicalJSON(normalized)
	if err != nil {
		return "", err
	}
	hash := sha256.Sum256(canonical)
	return hex.EncodeToString(hash[:]), nil
}

func canonicalJSON(value any) ([]byte, error) {
	var buffer bytes.Buffer
	var write func(any) error
	write = func(item any) error {
		switch current := item.(type) {
		case nil:
			buffer.WriteString("null")
		case bool:
			if current {
				buffer.WriteString("true")
			} else {
				buffer.WriteString("false")
			}
		case string:
			encoded, err := json.Marshal(current)
			if err != nil {
				return err
			}
			buffer.Write(encoded)
		case json.Number:
			buffer.WriteString(current.String())
		case []any:
			buffer.WriteByte('[')
			for i, child := range current {
				if i > 0 {
					buffer.WriteByte(',')
				}
				if err := write(child); err != nil {
					return err
				}
			}
			buffer.WriteByte(']')
		case map[string]any:
			keys := make([]string, 0, len(current))
			for key := range current {
				keys = append(keys, key)
			}
			sort.Strings(keys)
			buffer.WriteByte('{')
			for i, key := range keys {
				if i > 0 {
					buffer.WriteByte(',')
				}
				encoded, err := json.Marshal(key)
				if err != nil {
					return err
				}
				buffer.Write(encoded)
				buffer.WriteByte(':')
				if err := write(current[key]); err != nil {
					return err
				}
			}
			buffer.WriteByte('}')
		default:
			return fmt.Errorf("unsupported canonical JSON value %T", item)
		}
		return nil
	}
	if err := write(value); err != nil {
		return nil, err
	}
	return buffer.Bytes(), nil
}

func consumeJSON(decoder *json.Decoder) (any, error) {
	token, err := decoder.Token()
	if err != nil {
		return nil, err
	}
	delim, isDelim := token.(json.Delim)
	if !isDelim {
		return token, nil
	}
	switch delim {
	case '{':
		object := map[string]any{}
		for decoder.More() {
			keyToken, err := decoder.Token()
			if err != nil {
				return nil, err
			}
			key, ok := keyToken.(string)
			if !ok {
				return nil, errors.New("object key is not a string")
			}
			if _, exists := object[key]; exists {
				return nil, fmt.Errorf("duplicate JSON property %q", key)
			}
			value, err := consumeJSON(decoder)
			if err != nil {
				return nil, err
			}
			object[key] = value
		}
		end, err := decoder.Token()
		if err != nil || end != json.Delim('}') {
			return nil, errors.New("malformed JSON object")
		}
		return object, nil
	case '[':
		array := []any{}
		for decoder.More() {
			value, err := consumeJSON(decoder)
			if err != nil {
				return nil, err
			}
			array = append(array, value)
		}
		end, err := decoder.Token()
		if err != nil || end != json.Delim(']') {
			return nil, errors.New("malformed JSON array")
		}
		return array, nil
	default:
		return nil, errors.New("unexpected JSON delimiter")
	}
}
