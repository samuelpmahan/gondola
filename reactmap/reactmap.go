// Package reactmap holds the tables that map Gobi's DOM names to React's prop names. They live here once; `gobi emit
// react` writes them to react-map.gen.mjs for react-side.mjs.
package reactmap

import (
	"strings"

	"github.com/samuelpmahan/gondola/gobi"
)

// Pair is one table row.
type Pair struct{ From, To string }

// AttributeNames lists DOM attribute names that React spells differently, taken from gobi.AttributeNames so the table
// lives once. Names not listed pass through unchanged.
func AttributeNames() []Pair {
	var pairs []Pair
	for _, a := range gobi.AttributeNames {
		pairs = append(pairs, Pair{a.DOM, a.Prop})
	}
	return pairs
}

// EventNames maps a DOM event name to React's handler prop. Events not listed become "on" plus the name capitalised.
var EventNames = []Pair{
	{"click", "onClick"}, {"dblclick", "onDoubleClick"}, {"input", "onInput"}, {"change", "onChange"},
	{"submit", "onSubmit"}, {"reset", "onReset"}, {"select", "onSelect"}, {"keydown", "onKeyDown"}, {"keyup", "onKeyUp"},
	{"keypress", "onKeyPress"}, {"mouseenter", "onMouseEnter"}, {"mouseleave", "onMouseLeave"},
	{"mousedown", "onMouseDown"}, {"mouseup", "onMouseUp"}, {"mousemove", "onMouseMove"}, {"focus", "onFocus"},
	{"blur", "onBlur"}, {"scroll", "onScroll"}, {"wheel", "onWheel"}, {"touchstart", "onTouchStart"},
	{"touchend", "onTouchEnd"}, {"pointerdown", "onPointerDown"}, {"pointerup", "onPointerUp"}, {"load", "onLoad"},
	{"error", "onError"}, {"contextmenu", "onContextMenu"},
}

// StyleKey is gobi.StyleKey; Generate emits its JavaScript twin.
func StyleKey(property string) string { return gobi.StyleKey(property) }

// Generate returns the full text of react-map.gen.mjs.
func Generate() string {
	var b strings.Builder
	b.WriteString("// Generated by gobi from Go. Do not edit.\n")
	b.WriteString("export const attributeNames = {\n")
	writePairs(&b, AttributeNames())
	b.WriteString("};\n\nexport const booleanAttributes = [\n")
	for _, name := range gobi.BooleanAttributes {
		b.WriteString("  \"" + name + "\",\n")
	}
	b.WriteString("];\n\nexport const eventNames = {\n")
	writePairs(&b, EventNames)
	b.WriteString(`};

export function attributeName(name) {
  return Object.hasOwn(attributeNames, name) ? attributeNames[name] : name;
}

export function eventName(event) {
  return Object.hasOwn(eventNames, event) ? eventNames[event] : "on" + event[0].toUpperCase() + event.slice(1);
}

export function styleKey(property) {
  if (property.startsWith("--")) return property;
  const camel = (text) => text.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
  if (property.startsWith("-ms-")) return "ms" + camel("-" + property.slice(4));
  return camel(property);
}
`)
	return b.String()
}

func writePairs(b *strings.Builder, pairs []Pair) {
	for _, p := range pairs {
		b.WriteString("  \"" + p.From + "\": \"" + p.To + "\",\n")
	}
}
