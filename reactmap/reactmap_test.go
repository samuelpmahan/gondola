package reactmap

import (
	"strings"
	"testing"
)

func TestStyleKey(t *testing.T) {
	for _, c := range [][2]string{{"margin-top", "marginTop"}, {"-webkit-line-clamp", "WebkitLineClamp"}, {"-ms-filter", "msFilter"},
		{"--Mixed-Case", "--Mixed-Case"}, {"float", "float"}, {"", ""}} {
		if got := StyleKey(c[0]); got != c[1] {
			t.Errorf("StyleKey(%q) = %q want %q", c[0], got, c[1])
		}
	}
}

