import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
const taskRaw = resolve(ROOT, "compiled-children/coordination/rawlogs/E-FIX-HARNESS-LIVENESS-20261031-01");
const preservedRoot = resolve(ROOT, "compiled-children/coordination/repairs/E-FIX-HARNESS-LIVENESS/originals");
const canonical = {
  report: resolve(ROOT, "compiled-children/coordination/reports/E-HARNESS.md"),
  receipt: resolve(ROOT, "compiled-children/coordination/receipts/E-HARNESS.json"),
};
const copied = {
  report: resolve(taskRaw, "auto-generated-E-HARNESS.report.md"),
  receipt: resolve(taskRaw, "auto-generated-E-HARNESS.receipt.json"),
};
const original = {
  report: resolve(preservedRoot, "E-HARNESS.md"),
  receipt: resolve(preservedRoot, "E-HARNESS.json"),
};
const sha = (bytes) => createHash("sha256").update(bytes).digest("hex");

const [generatedReport, generatedReceiptBytes, manifest] = await Promise.all([
  readFile(canonical.report),
  readFile(canonical.receipt),
  readFile(resolve(preservedRoot, "manifest.json"), "utf8").then(JSON.parse),
]);
const generatedReceipt = JSON.parse(generatedReceiptBytes.toString("utf8"));
assert.equal(generatedReceipt.job_id, "E-HARNESS");
assert.equal(generatedReceipt.worker, "N4");
assert.equal(generatedReceipt.status, "matched");
assert.ok(generatedReceipt.invocation?.some((part) => String(part).includes("E-FIX-HARNESS-LIVENESS-20261031-01/replay")),
  "auto-written canonical receipt is not the recorded N6 replay attempt");

await Promise.all([
  writeFile(copied.report, generatedReport, { flag: "wx" }),
  writeFile(copied.receipt, generatedReceiptBytes, { flag: "wx" }),
]);
const generatedPins = {
  report: { path: "compiled-children/coordination/rawlogs/E-FIX-HARNESS-LIVENESS-20261031-01/auto-generated-E-HARNESS.report.md",
    bytes: generatedReport.length, sha256: sha(generatedReport) },
  receipt: { path: "compiled-children/coordination/rawlogs/E-FIX-HARNESS-LIVENESS-20261031-01/auto-generated-E-HARNESS.receipt.json",
    bytes: generatedReceiptBytes.length, sha256: sha(generatedReceiptBytes) },
};

const originalPins = {};
for (const key of ["report", "receipt"]) {
  const entry = manifest.files.find((item) => item.preserved === `compiled-children/coordination/repairs/E-FIX-HARNESS-LIVENESS/originals/${key === "report" ? "E-HARNESS.md" : "E-HARNESS.json"}`);
  assert.ok(entry, `preservation manifest has no original ${key}`);
  const bytes = await readFile(original[key]);
  assert.equal(bytes.length, entry.bytes, `preserved original ${key} length mismatch`);
  assert.equal(sha(bytes), entry.sha256, `preserved original ${key} hash mismatch`);
  originalPins[key] = { path: entry.preserved, bytes: bytes.length, sha256: sha(bytes) };
  await writeFile(canonical[key], bytes);
}

const restoredPins = {};
for (const key of ["report", "receipt"]) {
  const bytes = await readFile(canonical[key]);
  assert.equal(bytes.length, originalPins[key].bytes, `restored canonical ${key} length mismatch`);
  assert.equal(sha(bytes), originalPins[key].sha256, `restored canonical ${key} hash mismatch`);
  restoredPins[key] = {
    path: key === "report" ? "compiled-children/coordination/reports/E-HARNESS.md" : "compiled-children/coordination/receipts/E-HARNESS.json",
    bytes: bytes.length,
    sha256: sha(bytes),
  };
}

const record = {
  schema: "gobi.e-fix-harness-liveness-canonical-custody/v1",
  incident: "The first fresh N6 conformance replay auto-wrote N4-labeled canonical E-HARNESS files through the existing runner side effect.",
  attribution: "This is a writer-side labeling incident, not a native scheduler dispatch. No N4 task dispatch was initiated by this replay.",
  savedAutoOutput: generatedPins,
  originalBackup: originalPins,
  restoredCanonical: restoredPins,
  newCapturePreservedAt: "compiled-children/coordination/rawlogs/E-HARNESS-20261031T125654.208Z-2",
  status: "original canonical report and receipt restored byte-for-byte; fresh N6 replay outputs and auto-generated bytes retained",
};
await writeFile(resolve(taskRaw, "canonical-custody-restoration.json"), `${JSON.stringify(record, null, 2)}\n`, { flag: "wx" });
process.stdout.write(`${JSON.stringify(record, null, 2)}\n`);
